import assert from 'node:assert/strict';
import {cloneInitialState,giveControl,getLegalMoves,resolveMoveAttempt,escapeHold} from './match-engine.js';
const hit=(s,id)=>resolveMoveAttempt(s,{moveId:id,attackRoll:20,damageRoll:1});
let s=cloneInitialState();giveControl(s,'stone');
assert(!getLegalMoves(s).some(m=>m.id==='rebound-clothesline'));
assert(hit(s,'irish-whip').success);
assert.equal(s.ringPosition.zone,'ropes');
assert(getLegalMoves(s).some(m=>m.id==='rebound-clothesline'));
assert(hit(s,'rebound-clothesline').success);
assert.equal(s.ringPosition,null);
s=cloneInitialState();giveControl(s,'viper');
assert(hit(s,'corner-whip').success);
assert(getLegalMoves(s).some(m=>m.id==='corner-splash'));
assert(hit(s,'corner-splash').success);
s=cloneInitialState();giveControl(s,'stone');
assert(hit(s,'irish-whip').success);
assert(hit(s,'standing-headlock').success);
const escape=escapeHold(s,{escapeRoll:1});
assert(escape.success&&escape.ropeBreak,'ropes force clean break despite low escape roll');
assert.equal(s.phase,'NEUTRAL_ROLL');
console.log('Ring-position moves, contextual attacks and rope breaks PASS');
