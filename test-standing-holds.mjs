import assert from 'node:assert/strict';
import {cloneInitialState,giveControl,getLegalMoves,resolveMoveAttempt,escapeHold,availableHoldTransitions,transitionHold,wrestler} from './match-engine.js';
const s=cloneInitialState();giveControl(s,'stone');
assert(getLegalMoves(s).some(m=>m.id==='standing-wristlock'));
assert(getLegalMoves(s).some(m=>m.id==='standing-headlock'));
const a=resolveMoveAttempt(s,{moveId:'standing-wristlock',attackRoll:20,damageRoll:1});
assert(a.success);assert.equal(s.phase,'HOLD_ESCAPE');
assert.equal(wrestler(s,'viper').posture,'standing');
const failed=escapeHold(s,{escapeRoll:1});
assert(failed.ok&&!failed.success);
assert(availableHoldTransitions(s).some(m=>m.id==='standing-headlock'));
assert(transitionHold(s,{moveId:'standing-headlock'}).ok);
assert.equal(s.phase,'HOLD_ESCAPE');
const reversed=escapeHold(s,{escapeRoll:20});
assert(reversed.success&&reversed.reversal);
assert.equal(s.activeWrestlerId,'viper');
assert.equal(s.roles.viper,'H');
assert.equal(s.activeHold,null);
const v=cloneInitialState();giveControl(v,'viper');
assert(getLegalMoves(v).some(m=>m.id==='standing-headlock'));
assert(resolveMoveAttempt(v,{moveId:'standing-headlock',attackRoll:20,damageRoll:1}).success);
assert.equal(escapeHold(v,{escapeRoll:20}).success,true);
console.log('Standing hold escapes, transitions and reversal PASS');
