import assert from 'node:assert/strict';
import {cloneInitialState,giveControl,getLegalMoves,resolveMoveAttempt,wrestler,
  beginNeutral,resolveNeutralRoll} from './match-engine.js';
import {demoMoves} from './moves.js';
import {animationByMove} from './combat-animation-map.js';
assert(demoMoves.some(move=>move.id==='collar-elbow-tie-up'));
assert.equal(animationByMove['collar-elbow-tie-up'].choreography,'lockup');
const state=cloneInitialState();
giveControl(state,'stone');
assert(getLegalMoves(state).some(move=>move.id==='collar-elbow-tie-up'));
const tie=resolveMoveAttempt(state,{moveId:'collar-elbow-tie-up',attackRoll:1,damageRoll:0});
assert(tie.success);
assert.equal(state.standingTieUp.holderId,'stone');
assert.equal(state.phase,'ACTION_SELECT');
assert.equal(wrestler(state,'viper').posture,'standing');
const follow=resolveMoveAttempt(state,{moveId:'body-slam',attackRoll:20,damageRoll:5});
assert.equal(follow.tieUpBonus,2);
assert.equal(state.standingTieUp,null,'tie-up is consumed by follow-up');
const fresh=cloneInitialState();giveControl(fresh,'stone');
resolveMoveAttempt(fresh,{moveId:'collar-elbow-tie-up',attackRoll:1,damageRoll:0});
beginNeutral(fresh);
assert.equal(fresh.standingTieUp,null,'new neutral clears grapple advantage');
const newState=cloneInitialState();giveControl(newState,'viper');
assert(getLegalMoves(newState).some(move=>move.id==='collar-elbow-tie-up'),'both styles may lock up');
resolveMoveAttempt(newState,{moveId:'collar-elbow-tie-up',attackRoll:1,damageRoll:0});
const reversal=resolveMoveAttempt(newState,{moveId:'hip-toss',attackRoll:1,damageRoll:1});
assert.equal(reversal.tieUpBonus,2);
assert.equal(newState.standingTieUp,null);
console.log('Standing tie-up to grapple and counter-window tests PASS');
